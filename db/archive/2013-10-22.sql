CREATE TABLE `users_calls` (
`id` MEDIUMINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY ,
`user_id` MEDIUMINT UNSIGNED NOT NULL DEFAULT '0' COMMENT 'Пользователь создавший обзвон',
`name` VARCHAR( 255 ) NOT NULL DEFAULT '',
`date` DATE NOT NULL ,
`sex` TINYINT NOT NULL DEFAULT '0',
`shop` VARCHAR( 255 ) NOT NULL ,
`brands` VARCHAR( 1024 ) NOT NULL COMMENT 'Бренды через запятую',
`sum_min` INT UNSIGNED NOT NULL DEFAULT '0',
`sum_max` INT UNSIGNED NOT NULL DEFAULT '0'
) ENGINE = MYISAM CHARACTER SET utf8 COLLATE utf8_general_ci;

CREATE TABLE `users_calls_log` (
`id` INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY ,
`user_id` MEDIUMINT UNSIGNED NOT NULL DEFAULT '0',
`call_id` MEDIUMINT UNSIGNED NOT NULL DEFAULT '0',
`status` TINYINT UNSIGNED NOT NULL DEFAULT '0' COMMENT '0 - не звонили, 1 - не дозвонились, 2 - дозвонились',
`date_created` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ,
`caller_id` MEDIUMINT UNSIGNED NOT NULL
) ENGINE = MYISAM CHARACTER SET utf8 COLLATE utf8_general_ci;
